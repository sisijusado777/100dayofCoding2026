public class day06 {
    public static void main(String[] args) {

        //membuat satu karakter menggunakan tipe data char
        char jenisKelamin = 'L';

        //membuat variabel dengan tipe data char untuk menyimpan satu huruf
        char nilai = 'A';

        //membuat variabel dengan tpe data boolean untuk menyimpan nilai benar/salah
        boolean mahasiswa = true;

        //membuat variabel boolean untuk menunjukkan apakah sudah lulus
        boolean lulus = false;


        //menampilkan judul program
        System.out.println("DATA CHAR DAN BOOLEAN");

        //menampilkan nilai dari jenis kelamin
        System.out.println("Jenis Kelamin (char)    : " + jenisKelamin);

        //menampilkan hasil dari variabel  char nilai
        System.out.println("Nilai (char)            : " + nilai);

        //menampilkan variabel dari boolean mahasiswa
        System.out.println("Mahasiswa (boolean)     : " + mahasiswa);

        //menampilkan variabel dari boolean lulus
        System.out.println("Lulus (boolean)         : " + lulus);
    }
    
}
