public class day09 {
    public static void main(String[] args) {
        //membuat konstanta dengan tipe data string
        //kata kunci final membuat nilai variabel tidak dapat di ubah lagi
        final String nama = "Sisi Jusado";

        // membuat konstanta dengan tipe data int untuk menyimpan NIM
        final int nim = 224039;

        //mebuat konstanta dengan tipe data double untuk menyimpan nilai ipk
        final double ipk = 3.55;

        //menampilkan judul
        System.out.println("DATA KONSTANTA");

        //menampilkan hasil konstanta nama
        System.out.println("Nama    : " + nama);

        //menampilkan hasil konstanta nim
        System.out.println("NIM     : " + nim);

        System.out.println("IPK     : " + ipk);

        // nilai konstanta tidak dapat diubah
    }

    
}
