public class day04 {
    public static void main(String[] args) {

        //ini tipe data byte
        byte umur = 19;

        //ini tipe data short
        short tahunLahir = 2007;

        //ini tipe data int
        int nim = 224039;

        //ini tipe data long
        long jumlahPenduduk = 2900000000L;

        //menampilkan judul program
        System.out.println("DATA NUMERIK BILANGAN BULAT");

        //menampilkan nilai variabel Byte
        System.out.println("Byte    (umur)              : " + umur);

        //menampilkan nilai variabel Short
        System.out.println("Short   (tahun lahir)       : " + tahunLahir);

        //menampilkan nilai variabel Int
        System.out.println("Int     (NIM)               : " + nim);

        //menampilkan nilai variabel Long
        System.out.println("Long    (jumlah penduduk)   : " + jumlahPenduduk);
    }
}
