public class day05 {
    public static void main(String[] args) {

        //membuat variabel dengan tipe data float untuk menyimpan nilai pecahan 
        //huruf f digunakan untuk menandakan bahwa nilai tersebut bertipe float
        float tinggiBadan = 165.5f;

        //membuat variabel dengan tipe data double untuk menyimpan nilai pecahan
        double beratBadan = 55.75;

        //menampilkan judul program
        System.out.println("TIPE DATA PECAHAN : ");

        //menampilkan nilai dari variabel float
        System.out.println("Tinggi badan (float)    : " + tinggiBadan);

        //menampilkan nilai dari variabel double
        System.out.println("Berat badan (double)    : " + beratBadan);
    }
}
