public class day08 {
    public static void main(String[] args) {
        
        //deklarasi variabel dengan tipe data string tanpa memberi nilai
        String nama;

        //inisialisasi variabel nama dengan memberikan nilai awal
        nama = "Sisi Jusado";

        //deklarasi dan inisialisasi variabel umur secara langsung
        int umur = 19;

        //menampilkan nilai awal dari variabel nama
        System.out.println("Nama awal       : " + nama);

        //menampilkan nilai awal dari variabel umur
        System.out.println("Umur awal       : " + umur);

        //mengupdate nilai variabel nama
        nama = "Sisi";

        //mengupdate nilai variabel umur
        umur = 20;


        //menampilkan nilai nama setelah update

        System.out.println("Nama baru       : " + nama);

        //menampilkan nilai umur setelah update
        System.out.println("Umur baru       : " + umur);
    }
}
