public class day03 {
    public static void main(String[] args) {

        //menggunakan \n untuk membuat baris baru
        System.out.println("Nama    : Sisi Jusado\nNIM     : D0224039");

        //menggunakan \t untuk membuat jarak seperti tab
        System.out.println("Nama\t: Sisi Jusado");
        System.out.println("NIM\t: D0224039");

        //menggunakan \" untuk menampilkan tanda petik
        System.out.println("Dia berkata, \"Saya sedang ngoding.\"");

        //menggunakan \\ untuk menampilkan tanda backlash
        System.out.println("Lokasi file: C:\\Users\\lenovo\\Documents\\day100" );

        //menggunakan \b untuk menghapus satu karakter sebelumnya
        System.out.println("Javva\b");

        //menggunakan \r untuk kembali ke awal baris
        System.out.println("Belajar\rJava");
    }
}
